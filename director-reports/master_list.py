#!/usr/bin/env python3
"""MASTER WORK LIST generator — DellMatrix.

Single computation point for the master work list (Ace ruling 2026-11-10:
the "72" framing is retired; ONE numbered list, a real percentage).

Reads the data file (master_work_list_items.json: [{n, title, ids, status,
block}]), validates it, computes the headline STRICT percentage
(COMPLETE / total — no partial credit, no blending; partial work is visible
as statuses, never as fractional completion), and renders the markdown
list deterministically. Every surface that shows the number (chat, state
file, queue, reports) quotes this script's output — nobody hand-writes it.

Usage:
  python3 master_list.py [--data PATH] [--out PATH] [--line]

--line prints only the one-line summary for the state file / cycle log:
  MWL 25/182 COMPLETE = 13.7% | MERGED_UNVERIFIED 4 | BUILT_HELD 2 | ...
"""
import argparse
import json
import sys
from collections import Counter, OrderedDict

STATUSES = [
    "COMPLETE",
    "MERGED_UNVERIFIED",
    "BUILT_HELD",
    "PARTIAL",
    "OPEN",
    "GATED",
    "NEEDS_OVERSEER",
    "SANDBOXED",
]


def load_and_validate(path):
    items = json.load(open(path))
    errors = []
    ns = [i["n"] for i in items]
    if ns != list(range(1, len(items) + 1)):
        errors.append(f"numbering not sequential 1..{len(items)}")
    for i in items:
        if i["status"] not in STATUSES:
            errors.append(f"item {i['n']}: unknown status {i['status']!r}")
        if not i.get("title") or not i.get("ids") or not i.get("block"):
            errors.append(f"item {i['n']}: missing title/ids/block")
    if errors:
        for e in errors:
            print(f"VALIDATION ERROR: {e}", file=sys.stderr)
        sys.exit(2)
    return items


def summarize(items):
    counts = Counter(i["status"] for i in items)
    total = sum(1 for i in items if i["status"] != "SANDBOXED")
    complete = counts["COMPLETE"]
    pct = (100.0 * complete / total) if total else 0.0
    return counts, total, complete, pct


def one_line(items):
    counts, total, complete, pct = summarize(items)
    parts = [f"MWL {complete}/{total} COMPLETE = {pct:.1f}%"]
    for s in STATUSES[1:]:
        if s != "SANDBOXED" and counts[s]:
            parts.append(f"{s} {counts[s]}")
    if counts["SANDBOXED"]:
        parts.append(f"SANDBOXED {counts['SANDBOXED']} (outside active scope)")
    return " | ".join(parts)


def render(items, data_note):
    counts, total, complete, pct = summarize(items)
    out = []
    out.append("# MASTER WORK LIST — DellMatrix / Mandell / DuoBeta")
    out.append("")
    out.append("Ordered by Ace (Overseer), 2026-11-10: the \"72\" framing is retired")
    out.append("as the headline scoreboard. This list numbers EVERYTHING that has to")
    out.append("be done in one enumeration, with a real percentage against 100%.")
    out.append("GENERATED by master_list.py from the master data file — do not")
    out.append("hand-edit the numbers; edit the data and re-render.")
    out.append(f"Data: {data_note}")
    out.append("")
    out.append("## Counting rules")
    out.append("")
    out.append("- One line = one distinct unit of work. A register row, a plan card,")
    out.append("  and a defect ID describing the same work are ONE item naming every ID.")
    out.append("- Statuses: COMPLETE (authority-confirmed closed), MERGED_UNVERIFIED")
    out.append("  (merged, final-check pending), BUILT_HELD (built, awaiting authority")
    out.append("  disposition or merge-step conditions), PARTIAL (verified work exists,")
    out.append("  scope unclosed), OPEN (not started / investigation only), GATED")
    out.append("  (deliberately held: save-path / Q1 / R-2 class), NEEDS_OVERSEER")
    out.append("  (parked on Ace).")
    out.append("- HEADLINE % = COMPLETE / total. No partial credit and no blending:")
    out.append("  partial work is visible in the statuses, never converted into")
    out.append("  fractional completion (Ace epistemic doctrine, 2026-11-10).")
    out.append("")
    out.append("## The count")
    out.append("")
    out.append(f"**PROGRESS: {complete} / {total} COMPLETE = {pct:.1f}%**")
    out.append("")
    out.append("| Status | Items |")
    out.append("|---|---|")
    for s in STATUSES:
        if s == "SANDBOXED":
            continue
        out.append(f"| {s} | {counts[s]} |")
    out.append(f"| **TOTAL (active)** | **{total}** |")
    if counts["SANDBOXED"]:
        out.append("")
        out.append(f"Outside active scope: {counts['SANDBOXED']} SANDBOXED items (parked by Ace,")
        out.append("listed in their own block below; not counted in the total or the %).")
    out.append("")
    out.append("Continuity with the retired frame (different denominator, not a")
    out.append("regression): on the 72 register rows alone, strict completion is")
    out.append("19/72 = 26.4% and the register OCI is 55.7%. This list's denominator")
    out.append("also counts the plan's future circuits, the vision items, and the")
    out.append("parked items the 72 frame never counted.")
    blocks = OrderedDict()
    for i in items:
        blocks.setdefault(i["block"], []).append(i)
    for block, rows in blocks.items():
        out.append("")
        out.append(f"## Block {block}")
        out.append("")
        out.append("| # | Item | Source IDs | Status |")
        out.append("|---|---|---|---|")
        for i in rows:
            title = i["title"].replace("|", "/")
            out.append(f"| {i['n']} | {title} | {i['ids']} | {i['status']} |")
    out.append("")
    return "\n".join(out)


KNOWN_ABSENT = {"DD-33", "SM-53"}  # grep-verified absent from plan + register (coverage report)


def census(items):
    """Mechanical presence census: which series IDs appear in items' ids fields.
    Presence is NOT proof of correct deduplication or coverage — it is a
    tripwire that fails loudly when an expected ID vanishes from the data.
    The auditable coverage argument lives in master_work_list_coverage.md."""
    import re as _re
    found = set()
    for i in items:
        found |= set(_re.findall(r"(?:DD|SM|V|G)-\d+|72-\d+", i["ids"]))
    missing = []
    for prefix, hi in (("DD-", 54), ("72-", 72)):
        for k in range(1, hi + 1):
            tok = f"{prefix}{k:02d}"
            if tok not in found and tok not in KNOWN_ABSENT:
                missing.append(tok)
    return found, missing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="master_work_list_items.json")
    ap.add_argument("--out", default=None)
    ap.add_argument("--line", action="store_true")
    ap.add_argument("--check", default=None,
                    help="re-render and byte-diff against this committed render; exit 3 on drift")
    ap.add_argument("--census", action="store_true",
                    help="print the series-ID presence census and fail on unexpected absences")
    args = ap.parse_args()
    items = load_and_validate(args.data)
    if args.census:
        found, missing = census(items)
        print(f"census: {len(found)} series IDs present; unexpected absences: {missing}")
        if missing:
            sys.exit(4)
    if args.check:
        rendered = render(items, args.data)
        existing = open(args.check).read()
        if rendered != existing:
            print(f"RENDER DRIFT: {args.check} differs from a fresh render of {args.data}", file=sys.stderr)
            sys.exit(3)
        print(f"render check OK: {args.check} is byte-identical to a fresh render")
    if args.line:
        print(one_line(items))
        return
    md = render(items, args.data)
    if args.out:
        open(args.out, "w").write(md)
        print(f"rendered {args.out}: {one_line(items)}")
    else:
        print(md)


if __name__ == "__main__":
    main()
