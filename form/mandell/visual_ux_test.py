"""Phase N — rich visual UX (README Completion Program).

README section 2 carried two visual rows: the offline snapshot export
was WORKING with "in-browser rendering untested", and "Rich visual UX"
was PLANNED with "interactive UI planned". Grounding at b78ba08 found
the snapshot was already interactive (embedded JSON, click-to-inspect)
but had exactly one missing program-named interaction and two drift
defects:

  - NO filter/search control existed in plane_to_html (visual.py) —
    the only "filter" hits were an SVG glow filter and a CSS filter;
  - assets/js/core.js PAGES had NO nature_code entry, so the
    nature_code page — routed by live_visual (/nature, /nature_code,
    /noc) and present under assets/pages/ — was unreachable from the
    shared navigation;
  - page_enhance_loop.PAGE_FILES covered only 9 of the 12 pages
    (missing nature_code, inspire, workshops).

This phase:
  - adds a filter/search control to the snapshot export: an input
    (#node-filter) wired to applyFilter/nodeMatches over the embedded
    NODES payload (label, words, skin, id, detail), hiding non-matching
    SVG nodes and reporting the match count — still single-file,
    still zero network by construction;
  - adds nature_code to the shared nav (core.js PAGES);
  - completes page_enhance_loop.PAGE_FILES to all 12 pages;
  - registers THIS suite as the canonical-runner coverage the surface
    never had.

Proof standard: the export is generated through the real REPL
`visual` command (REAL_USER_PATH, separate OS process); the generated
page's own inline script is then EXECUTED under Node with a minimal
DOM stub (showNode inspect binding + the filter behavior are run, not
string-matched); offline-ness is asserted on the generated bytes;
route/nav/enhance-list consistency is checked against the actual
_PAGE_ROUTES, core.js, and assets/pages/ contents. Pixel rendering in
a commercial browser is NOT claimed here (see the phase packet).

Isolation: unique owner per run. Cleanup removes exactly the owner's
generated visual outputs via canonical paths; a cleanup failure other
than an absent file fails loudly.
"""

from __future__ import annotations

import glob
import json
import os
import re
import shutil
import subprocess
import sys
import uuid

CHECKS: list = []

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OWNER = "VisualUX" + uuid.uuid4().hex[:6]


def check(name: str, cond: bool, detail: str = "") -> bool:
    CHECKS.append((name, bool(cond), detail))
    return bool(cond)


def _cleanup() -> None:
    pats = [
        os.path.join(ROOT, "form", "state", "visual", f"matrix_{OWNER}.*"),
        os.path.join(ROOT, "form", "state", f"program_{OWNER}.json"),
        os.path.join(ROOT, "form", "state", f"nursery_{OWNER}.json"),
        os.path.join(ROOT, "form", "state", f"checkpoint_{OWNER}_*"),
    ]
    for pat in pats:
        for p in glob.glob(pat):
            try:
                os.remove(p)
            except FileNotFoundError:
                pass
            except OSError as e:  # loud, per program cleanup law
                raise AssertionError(f"cleanup failed for {p}: {e}")


def _repl(lines: list[str]) -> str:
    proc = subprocess.run(
        [sys.executable, "-m", "form.repl", "--owner", OWNER],
        input="\n".join(lines) + "\n",
        capture_output=True, text=True, cwd=ROOT, timeout=300,
    )
    return proc.stdout + proc.stderr


def _extract_script(html_text: str) -> str:
    blocks = re.findall(r"<script>(.*?)</script>", html_text, re.S)
    assert blocks, "no inline script block in generated export"
    return max(blocks, key=len)


def _run_dom_harness(html_text: str, nodes: list, target: dict,
                     filter_token: str) -> dict:
    # Filter token = a grown link node's full suffixed id: label words
    # legitimately recur across related nodes (the filter finding a node
    # AND its link nodes is correct behavior), while a full link id
    # occurs in exactly one node's haystack.
    token = filter_token
    """Execute the page's own script under Node with a DOM stub.

    Returns the driver's printed key:value lines. The stub implements
    exactly the DOM surface the template uses (getElementById,
    querySelector(All) over .node elements, createElement, classList,
    addEventListener, clipboard). This executes the real showNode and
    applyFilter code from the generated file — not a reimplementation.
    """
    script = _extract_script(html_text)
    ids = [n["id"] for n in nodes]
    first = target
    prelude = """
class El {
  constructor(tag) {
    this.tagName = tag || 'div'; this.children = []; this.style = {};
    this._attrs = {}; this._listeners = {}; this.textContent = '';
    this.innerHTML = ''; this.className = ''; this.value = '';
    const s = new Set();
    this.classList = { add: (c) => s.add(c), remove: (c) => s.delete(c),
                       contains: (c) => s.has(c) };
  }
  setAttribute(k, v) { this._attrs[k] = String(v); }
  getAttribute(k) { return (k in this._attrs) ? this._attrs[k] : null; }
  addEventListener(t, f) { (this._listeners[t] = this._listeners[t] || []).push(f); }
  appendChild(c) { this.children.push(c); return c; }
}
const __nodeEls = __IDS__.map(id => {
  const e = new El('g'); e.setAttribute('data-id', id); e.className = 'node';
  return e;
});
const __byIdEl = {};
const document = {
  getElementById(id) {
    if (!__byIdEl[id]) __byIdEl[id] = new El('div');
    return __byIdEl[id];
  },
  querySelectorAll(sel) {
    if (sel === '.node') return __nodeEls;
    return [];
  },
  querySelector(sel) {
    const m = /data-id="([^"]+)"/.exec(sel);
    if (m) return __nodeEls.find(e => e.getAttribute('data-id') === m[1]) || null;
    if (sel === '.node') return __nodeEls[0] || null;
    return null;
  },
  createElement(tag) { return new El(tag); },
};
const navigator = { clipboard: { writeText: async (t) => {} } };
const window = globalThis;
""".replace("__IDS__", json.dumps(ids))
    driver = """
showNode(__FIRST__);
console.log('TITLE=' + document.getElementById('p-title').textContent);
console.log('PAGE_CMD=' + document.getElementById('p-page').textContent);
const __n1 = applyFilter(__TOKEN__);
console.log('FILTER_ONE=' + __n1);
console.log('VISIBLE_ONE=' + __nodeEls.filter(g => g.style.display !== 'none').length);
const __nAll = applyFilter('');
console.log('FILTER_ALL=' + __nAll);
const __n0 = applyFilter('zzqqnomatch');
console.log('FILTER_NONE=' + __n0);
console.log('FILTER_LISTENER=' + ((document.getElementById('node-filter')._listeners['input'] || []).length));
""".replace("__FIRST__", json.dumps(first["id"])).replace(
        "__TOKEN__", json.dumps(token))
    src = prelude + "\n" + script + "\n" + driver
    tmp = os.path.join(ROOT, "form", "state", f"_vux_harness_{OWNER}.js")
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(src)
    try:
        proc = subprocess.run(["node", tmp], capture_output=True, text=True,
                              cwd=ROOT, timeout=120)
    finally:
        try:
            os.remove(tmp)
        except FileNotFoundError:
            pass
        except OSError as e:
            raise AssertionError(f"harness cleanup failed for {tmp}: {e}")
    out = {}
    for line in proc.stdout.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    out["_rc"] = proc.returncode
    out["_stderr"] = proc.stderr[-400:]
    return out


def smoke() -> bool:
    CHECKS.clear()
    _cleanup()
    try:
        # --- generate through the real REPL user path ----------------
        out = _repl([
            "create an idea called alphafern",
            "create an idea called betastone",
            "grow ideas 2",
            "confirm all",
            "visual",
            "quit",
        ])
        html_path = os.path.join(ROOT, "form", "state", "visual",
                                 f"matrix_{OWNER}.html")
        check("repl_visual_writes_html", os.path.isfile(html_path),
              out[-200:] if not os.path.isfile(html_path) else "")
        if not os.path.isfile(html_path):
            return _verdict()
        with open(html_path, encoding="utf-8") as fh:
            page = fh.read()

        m = re.search(r"const NODES = (\[.*?\]);", page, re.S)
        nodes = json.loads(m.group(1)) if m else []
        labels = {n.get("label", "") for n in nodes}
        check("export_has_both_ideas_on_plane",
              {"alphafern", "betastone"} <= labels, str(labels))

        # --- the filter control exists and is wired -------------------
        check("filter_input_present", 'id="node-filter"' in page)
        check("filter_logic_present",
              "function applyFilter" in page and "function nodeMatches" in page)
        check("filter_listener_wired", "node-filter" in page
              and "addEventListener('input'" in page)

        # --- offline by construction ----------------------------------
        bad = [p for p in (r'src="http', r'href="http', r"fetch\(",
                           r"XMLHttpRequest", r"WebSocket")
               if re.search(p, page)]
        check("export_zero_network_refs", not bad, str(bad))

        # --- execute the page's own script (Node DOM stub) ------------
        node_bin = shutil.which("node")
        if node_bin and len(nodes) >= 2:
            first = next(n for n in nodes if n.get("label") == "alphafern")
            link_node = max(nodes, key=lambda n: len(n.get("id", "")))
            res = _run_dom_harness(page, nodes, first, link_node["id"])
            check("dom_script_runs", res.get("_rc") == 0, res.get("_stderr", ""))
            check("dom_showNode_inspects",
                  res.get("TITLE") == "alphafern"
                  and res.get("PAGE_CMD") == "zoom " + first["id"],
                  str({k: res.get(k) for k in ("TITLE", "PAGE_CMD")}))
            check("dom_filter_narrows_to_one",
                  res.get("FILTER_ONE") == "1" and res.get("VISIBLE_ONE") == "1",
                  str({k: res.get(k) for k in ("FILTER_ONE", "VISIBLE_ONE")}))
            check("dom_filter_clear_restores_all",
                  res.get("FILTER_ALL") == str(len(nodes)),
                  res.get("FILTER_ALL", ""))
            check("dom_filter_no_match_zero",
                  res.get("FILTER_NONE") == "0", res.get("FILTER_NONE", ""))
            check("dom_filter_input_listener_live",
                  res.get("FILTER_LISTENER", "0") not in ("", "0"),
                  res.get("FILTER_LISTENER", ""))
        elif not node_bin:
            print("  SKIP: node not available — DOM execution checks skipped "
                  "(structural checks above still stand)")
        else:
            check("dom_needs_two_nodes", False, f"nodes={len(nodes)}")

        # --- empty plane still exports a working shell ----------------
        sys.path.insert(0, ROOT)
        from form.dell_matrix.plane import Plane
        from form.dell_matrix.visual import plane_to_html
        empty_html = plane_to_html(Plane(), owner="EmptyCheck")
        check("empty_plane_has_filter_and_empty_nodes",
              'id="node-filter"' in empty_html and "const NODES = []" in empty_html)

        # --- nav / route / enhance-list consistency -------------------
        from form.dell_matrix import live_visual
        routes = set()
        for target in live_visual._PAGE_ROUTES.values():
            if target.startswith("pages/") and target.endswith(".html"):
                routes.add(os.path.basename(target)[:-5])
        core_js = open(os.path.join(ROOT, "form", "dell_matrix", "assets",
                                    "js", "core.js"), encoding="utf-8").read()
        nav_ids = set(re.findall(r"\{ id: '([a-z_]+)', href:", core_js))
        check("nav_covers_every_routed_page", routes <= nav_ids,
              f"missing={sorted(routes - nav_ids)}")
        check("nav_has_nature_code", "nature_code" in nav_ids)

        from form.dell_matrix import page_enhance_loop
        pages_dir = os.path.join(ROOT, "form", "dell_matrix", "assets", "pages")
        page_stems = {f[:-5] for f in os.listdir(pages_dir) if f.endswith(".html")}
        check("enhance_loop_covers_all_pages",
              page_stems <= set(page_enhance_loop.PAGE_FILES),
              f"missing={sorted(page_stems - set(page_enhance_loop.PAGE_FILES))}")

        # --- the pre-existing visual smoke still passes ---------------
        from form.dell_matrix.visual import smoke as visual_smoke
        check("visual_smoke_still_green", bool(visual_smoke()))
    finally:
        _cleanup()
    return _verdict()


def _verdict() -> bool:
    failed = [(n, d) for n, ok, d in CHECKS if not ok]
    for n, ok, d in CHECKS:
        print(f"  {'PASS' if ok else 'FAIL'}  {n}" + (f"  -- {d}" if (d and not ok) else ""))
    print(f"visual_ux_test: {len(CHECKS) - len(failed)}/{len(CHECKS)}")
    return not failed


if __name__ == "__main__":
    sys.exit(0 if smoke() else 1)
